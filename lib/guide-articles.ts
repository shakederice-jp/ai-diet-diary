export function guideArticleBySlug(slug: string) {
  return GUIDE_ARTICLES.find((article) => article.slug === slug) ?? null;
}

export function guideArticlePath(slug: string) {
  return `/guide/${slug}`;
}

export function guideInlinePlainText(value: string | readonly GuideInline[]) {
  if (typeof value === "string") {
    return value;
  }
  return value
    .map((part) => {
      if (typeof part === "string") {
        return part;
      }
      if ("cite" in part) {
        return `[${part.cite}]`;
      }
      return part.label;
    })
    .join("");
}

assertGuideCatalog(GUIDE_ARTICLES);

export function guideArticleCharCount(article: GuideArticle) {
  const parts: string[] = article.lead.map((paragraph) => guideInlinePlainText(paragraph));
  for (const block of article.blocks) {
    if (block.type === "h2" || block.type === "h3") {
      parts.push(block.text);
    } else if (block.type === "p") {
      parts.push(guideInlinePlainText(block.text));
    } else if (block.type === "ul") {
      for (const item of block.items) {
        parts.push(guideInlinePlainText(item));
      }
    } else if (block.type === "table") {
      parts.push(block.caption, ...block.headers, ...block.rows.flat());
    } else if (block.type === "faq") {
      for (const item of block.items) {
        parts.push(item.question, guideInlinePlainText(item.answer));
      }
    }
  }
  return [...parts.join("")].length;
}
